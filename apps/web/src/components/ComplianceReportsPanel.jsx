import { useState } from "react";
import useApi from "../hooks/useApi";
import { listReports, createReport } from "../services/complianceReportService";
import DataTable from "./ui/DataTable";
import StatusBadge from "./ui/StatusBadge";
import Button from "./ui/Button";
import Modal from "./ui/Modal";
import FormField from "./ui/FormField";

const REPORT_TYPE_OPTIONS = [
    { value: "RBA", label: "RBA" },
    { value: "NSSF", label: "NSSF" },
    { value: "INTERNAL", label: "Internal" },
];

const EMPTY_FORM = { report_type: "INTERNAL", period_start: "", period_end: "" };

const COLUMNS = [
    { key: "report_type", header: "Type" },
    { key: "period_start", header: "Period Start", render: (row) => new Date(row.period_start).toLocaleDateString() },
    { key: "period_end", header: "Period End", render: (row) => new Date(row.period_end).toLocaleDateString() },
    { key: "generated_by_name", header: "Generated By" },
    { key: "generated_by_role", header: "Role" },
    { key: "rba_status", header: "Status", render: (row) => <StatusBadge status={row.rba_status} /> },
    { key: "generated_at", header: "Generated At", render: (row) => new Date(row.generated_at).toLocaleString() },
];

/**
 * Shared panel used by both FUND_MANAGER's "Operational Reports" page and
 * REGULATOR's "Compliance Reports" page - both roles read/write the same
 * `compliance_reports` API (matching the enforce_compliance_report_generator_role
 * database rule that allows exactly these two roles).
 */
function ComplianceReportsPanel({ title, subtitle }) {
    const reportsApi = useApi(listReports, []);
    const [modalOpen, setModalOpen] = useState(false);
    const [form, setForm] = useState(EMPTY_FORM);
    const [submitting, setSubmitting] = useState(false);
    const [formError, setFormError] = useState("");

    function handleChange(e) {
        const { name, value } = e.target;
        setForm((prev) => ({ ...prev, [name]: value }));
    }

    async function handleSubmit(e) {
        e.preventDefault();
        setFormError("");
        setSubmitting(true);
        try {
            await createReport(form);
            setModalOpen(false);
            setForm(EMPTY_FORM);
            reportsApi.refetch();
        } catch (err) {
            setFormError(err.message || "Failed to create report.");
        } finally {
            setSubmitting(false);
        }
    }

    return (
        <div>
            <div className="page-header">
                <div>
                    <h1 className="page-title">{title}</h1>
                    <p className="page-subtitle">{subtitle}</p>
                </div>
                <Button variant="primary" onClick={() => setModalOpen(true)}>
                    + New Report
                </Button>
            </div>

            <DataTable
                columns={COLUMNS}
                rows={reportsApi.data}
                rowKey="report_id"
                loading={reportsApi.loading}
                error={reportsApi.error}
                onRetry={reportsApi.refetch}
                emptyMessage="No reports have been filed yet."
            />

            <Modal open={modalOpen} title="Create a report" onClose={() => setModalOpen(false)}>
                {formError && <div className="form-error" style={{ marginBottom: 12 }}>{formError}</div>}
                <form className="form-grid" onSubmit={handleSubmit}>
                    <FormField
                        id="report_type"
                        label="Report type"
                        as="select"
                        options={REPORT_TYPE_OPTIONS}
                        value={form.report_type}
                        onChange={handleChange}
                    />
                    <FormField
                        id="period_start"
                        label="Period start"
                        type="date"
                        value={form.period_start}
                        onChange={handleChange}
                        required
                    />
                    <FormField
                        id="period_end"
                        label="Period end"
                        type="date"
                        value={form.period_end}
                        onChange={handleChange}
                        required
                    />
                    <div className="form-actions">
                        <Button type="button" variant="secondary" onClick={() => setModalOpen(false)}>
                            Cancel
                        </Button>
                        <Button type="submit" variant="primary" loading={submitting}>
                            Create
                        </Button>
                    </div>
                </form>
            </Modal>
        </div>
    );
}

export default ComplianceReportsPanel;
