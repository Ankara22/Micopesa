import { lazy, Suspense } from "react";
import useApi from "../../hooks/useApi";
import { getComplianceOverview, getComplianceReports } from "../../services/regulatorApi";
import { StatCard } from "../../components/ui/Card";
import DataTable from "../../components/ui/DataTable";
import StatusBadge from "../../components/ui/StatusBadge";
import SkeletonLoader from "../../components/ui/SkeletonLoader";
import ErrorState from "../../components/ui/ErrorState";

const RegulatorComplianceChart = lazy(() => import("./RegulatorComplianceChart"));

function RegulatorDashboard() {
    const complianceApi = useApi(getComplianceOverview, []);
    const reportsApi = useApi(getComplianceReports, []);

    if (complianceApi.loading || reportsApi.loading) {
        return (
            <>
                <SkeletonLoader variant="metrics" count={4} label="Loading compliance metrics" />
                <SkeletonLoader variant="chart" label="Loading compliance chart" />
            </>
        );
    }
    if (complianceApi.error) {
        return <ErrorState message={complianceApi.error} onRetry={complianceApi.refetch} />;
    }

    const compliance = complianceApi.data || {};
    const auditHealth = compliance.audit_health || {};
    const reports = reportsApi.data || [];
    const latestReport = compliance.latest_rba_report;
    const reportStatusData = (compliance.rba_reports_by_status || []).map((item) => ({
        status: item.rba_status,
        reports: Number(item.count),
    }));
    const columns = [
        { key: "report_type", header: "Report type" },
        { key: "generated_by_name", header: "Generated by" },
        { key: "generated_by_role", header: "Role" },
        { key: "period_start", header: "Period start", render: (row) => new Date(row.period_start).toLocaleDateString() },
        { key: "period_end", header: "Period end", render: (row) => new Date(row.period_end).toLocaleDateString() },
        { key: "rba_status", header: "Status", render: (row) => <StatusBadge status={row.rba_status} /> },
        { key: "generated_at", header: "Generated", render: (row) => new Date(row.generated_at).toLocaleString() },
    ];

    return (
        <div>
            <div className="page-header">
                <div>
                    <h1 className="page-title">Regulator Dashboard</h1>
                    <p className="page-subtitle">Platform audit health, RBA report status, and compliance oversight.</p>
                </div>
            </div>

            {reportsApi.error && (
                <ErrorState message={reportsApi.error} onRetry={reportsApi.refetch} />
            )}

            <div className="stat-card-grid">
                <StatCard
                    label="Audit events (24 hours)"
                    value={auditHealth.events_last_24h ?? 0}
                    hint={auditHealth.last_event_at ? `Last event ${new Date(auditHealth.last_event_at).toLocaleString()}` : "No recent audit events"}
                />
                <StatCard
                    label="RBA compliance"
                    value={<StatusBadge status={compliance.rba_compliance_status} />}
                    hint={latestReport ? `Latest report ${latestReport.rba_status}` : "No RBA report filed"}
                />
                <StatCard
                    label="RBA parameter checks"
                    value={<StatusBadge status={compliance.rba_parameter_checks?.status} />}
                    hint={compliance.rba_parameter_checks?.details}
                />
                <StatCard label="Reports in oversight" value={reports.length} hint="Latest 500 reports" />
            </div>

            <Suspense fallback={<SkeletonLoader variant="chart" label="Loading compliance chart" />}>
                <RegulatorComplianceChart reportStatusData={reportStatusData} />
            </Suspense>

            <section className="section card">
                <h2 className="card-title">RBA report status</h2>
                {compliance.rba_reports_by_status?.length ? (
                    <div className="stat-card-grid">
                        {compliance.rba_reports_by_status.map((item) => (
                            <StatCard
                                key={item.rba_status}
                                label={item.rba_status}
                                value={item.count}
                            />
                        ))}
                    </div>
                ) : (
                    <p>No RBA reports are available for review.</p>
                )}
                <p className="page-subtitle">
                    RBA-specific regulatory limits are not defined in the current database schema, so no threshold checks are asserted.
                </p>
            </section>

            <section className="section">
                <h2 className="card-title">Compliance Report Logs</h2>
                <DataTable
                    columns={columns}
                    rows={reports}
                    rowKey="report_id"
                    loading={false}
                    error={reportsApi.error}
                    onRetry={reportsApi.refetch}
                    emptyMessage="No compliance reports have been filed."
                />
            </section>
        </div>
    );
}

export default RegulatorDashboard;
